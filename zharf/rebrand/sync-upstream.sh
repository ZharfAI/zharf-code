#!/usr/bin/env bash
# Brings an upstream T3 Code release into Zharf Code.
#
#   zharf/rebrand/sync-upstream.sh v0.1.13            # then: git merge upstream-rebranded
#   SYNC_BRANCH=try/v0.1.13 zharf/rebrand/sync-upstream.sh v0.1.13-nightly.20261125.5258
#
# Puts the tag's tree, rebranded by zharf/rebrand/rebrand.ts (with the tool from the current
# branch), on the `upstream-rebranded` branch (or $SYNC_BRANCH) as one commit whose parents are
# the previous rebranded commit and the tag, so the fork's history keeps upstream's. It installs
# the tag's dependencies (the catalogs are re-keyed with its gt CLI), then checks translations
# and types before committing. Merging into `main` is left to you; conflicts only appear where
# main's own commits changed the same lines (zharf/README.md).
#
# Never push upstream's tags to origin: release workflows there run on Zharf Code's tags.
set -euo pipefail

tag="${1:?usage: sync-upstream.sh <upstream tag> [--skip-checks]}"
skip_checks="${2:-}"
branch="${SYNC_BRANCH:-upstream-rebranded}"
repo="$(git rev-parse --show-toplevel)"
cd "$repo"

if [[ -n "$(git status --porcelain)" ]]; then
  echo "The work tree has changes; commit or remove them first." >&2
  exit 1
fi

git fetch --quiet --no-tags upstream "refs/tags/${tag}:refs/tags/${tag}"
tag_commit="$(git rev-list -n1 "$tag")"
start_branch="$(git branch --show-current)"
[[ -n "$start_branch" ]] || { echo "Run this from a branch (main), not a detached HEAD." >&2; exit 1; }

# The tool runs from a copy, because checking out the tag replaces zharf/ in the work tree.
tool="$(mktemp -d)"
restore() {
  rm -rf "$tool"
  git checkout --quiet --force "$start_branch"
}
trap restore EXIT
git archive "$start_branch" zharf | tar -x -C "$tool"

parents=(-p "$tag_commit")
if git rev-parse --verify --quiet "refs/heads/upstream-rebranded" >/dev/null; then
  parents=(-p "$(git rev-parse upstream-rebranded)" "${parents[@]}")
fi

git checkout --quiet --detach "$tag_commit"
echo "Installing ${tag}'s dependencies..."
pnpm install --frozen-lockfile --filter '!@t3tools/marketing' --filter '!t3code-relay' \
  --filter '!@t3tools/evals' >/dev/null
node "$tool/zharf/rebrand/rebrand.ts" --root "$repo"

if [[ "$skip_checks" != "--skip-checks" ]]; then
  node scripts/i18n-check.ts
  pnpm exec vp run --concurrency-limit 3 --filter './apps/server' --filter './apps/web' \
    --filter './apps/desktop' --filter './apps/mobile' --filter './packages/*' --filter './scripts' \
    typecheck
fi

git add -A
tree="$(git write-tree)"
commit="$(git commit-tree "$tree" "${parents[@]}" -m "Rebrand T3 Code ${tag} as Zharf Code

Generated by zharf/rebrand/rebrand.ts from upstream ${tag} (${tag_commit:0:10}).
Zharf Code is an unofficial fork based on the T3 Code source code; it is
not affiliated with, endorsed by, or maintained by T3 Tools, Inc.")"
git branch -f "$branch" "$commit"

echo "${branch} is now ${commit:0:10} (${tag})."
echo "Next: git merge ${branch}, then pnpm install (the lockfile may have changed)."
