#!/usr/bin/env bash
# Brings an upstream T3 Code release into Zharf Code.
#
#   zharf/rebrand/sync-upstream.sh v0.1.13
#
# 1. Puts the release's tree, rebranded by zharf/rebrand/rebrand.ts, on the `upstream-rebranded`
#    branch as one commit whose parents are the previous rebranded commit and the release tag,
#    so the fork's history keeps upstream's.
# 2. Leaves merging it into `main` to you: `git merge upstream-rebranded`. Conflicts only appear
#    where main's own commits changed the same lines (see zharf/README.md).
#
# Needs a clean work tree and installed dependencies (pnpm install), because the translation
# catalogs are re-keyed with the gt CLI.
set -euo pipefail

tag="${1:?usage: sync-upstream.sh <upstream tag>}"
repo="$(git rev-parse --show-toplevel)"
cd "$repo"

if [[ -n "$(git status --porcelain)" ]]; then
  echo "The work tree has changes; commit or remove them first." >&2
  exit 1
fi

git fetch --quiet upstream "refs/tags/${tag}:refs/tags/${tag}"
tag_commit="$(git rev-list -n1 "$tag")"
start_branch="$(git branch --show-current)"

# The tool runs from a copy, because checking out the release replaces zharf/ in the work tree.
tool="$(mktemp -d)"
trap 'rm -rf "$tool"' EXIT
git archive "$start_branch" zharf | tar -x -C "$tool"

parents=(-p "$tag_commit")
if git rev-parse --verify --quiet refs/heads/upstream-rebranded >/dev/null; then
  parents=(-p "$(git rev-parse upstream-rebranded)" "${parents[@]}")
fi

git checkout --quiet --detach "$tag_commit"
node "$tool/zharf/rebrand/rebrand.ts" --root "$repo"

git add -A
tree="$(git write-tree)"
commit="$(git commit-tree "$tree" "${parents[@]}" -m "Rebrand T3 Code ${tag} as Zharf Code

Generated by zharf/rebrand/rebrand.ts from upstream ${tag} (${tag_commit}).")"
git branch -f upstream-rebranded "$commit"
git checkout --quiet --force "$start_branch"

echo "upstream-rebranded is now ${commit:0:10} (${tag}). Next: git merge upstream-rebranded"
